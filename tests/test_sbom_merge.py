        self.assertIn("37 from the probe (29 with a lock entry), 9 lock-only", self.run_tool()[1])
        # same flag as with no probe document at all, and a second merge changes nothing
        self.merged(probe=self.probe_with(tini="mismatch"))
        first = read(self.out)
        self.merged(image=load(self.out), probe=self.probe_with(tini="mismatch"))
        self.assertEqual(read(self.out), first)

