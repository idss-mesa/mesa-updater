        self.assertEqual(len(props(tini, "mesa:lock:kind")), 1)
        self.assertEqual(tini["hashes"], [{"alg": "SHA-256", "content":
                                           "93dcc18adc78c65a028a84799ecf8ad40c936fdfc5f2a57b1acda5a8117fa82c"}])
        # the scanner saw go 1.27.3 under the pin's path: that is not lock-only, whatever the probe printed
        go = self.find(doc, "go", ptype="generic")
        self.assertEqual((prop(go, "mesa:probe:result"), prop(go, "mesa:merge:source")), ("mismatch", None))
