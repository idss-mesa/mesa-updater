    def test_pins(self):
        doc = self.merged()
        go = self.find(doc, "go", ptype="generic")  # scanner saw /usr/local/go/bin/go
        self.assertEqual(paths(go), ["/usr/local/go/bin/go"])
        self.assertEqual(go["cpe"], "cpe:2.3:a:golang:go:1.27.3:*:*:*:*:*:*:*")
        self.assertEqual(go["hashes"], [{"alg": "SHA-256", "content":
                                         "65efbc80fdc1fa2cd2631cad5b481777a68e8725f34e89f50fc6ac714e379b40"}])
        self.assertEqual(prop(go, "mesa:lock:path"), "/usr/local/go")
        self.assertEqual(prop(go, "mesa:probe:result"), "ok")
        self.assertEqual(len(props(go, "mesa:lock:kind")), 1)
        tini = self.find(doc, "tini")  # no scanner component; the probe ran it
        self.assertEqual((tini["version"], prop(tini, "mesa:probe:result")), ("v0.19.0", "ok"))
        self.assertIsNone(prop(tini, "mesa:merge:source"))
        # a pin's URL is a template, not an IRI: one property, and no distribution reference
        self.assertEqual(props(go, "mesa:lock:url"),
                         [("mesa:lock:url", "https://go.dev/dl/go{version}.linux-{arch}.tar.gz")])
        self.assertNotIn("externalReferences", tini)
        self.assertFalse([r for c in doc["components"] for r in c.get("externalReferences", [])
                          if "{" in r.get("url", "")])
        # claude-code is both an npm lock entry and a pin: one component, both recorded
        claude = self.find(doc, "@anthropic-ai/claude-code")
        self.assertEqual(sorted(v for _, v in props(claude, "mesa:lock:kind")), ["npm", "pins"])
        # a pin's path only claims components of the pin's own purl
        self.assertEqual(props(self.find(doc, "github.com/cyverse/gocommands"), "mesa:"), [])

    def probe_with(self, **results):
        probe = load("probe.cdx.json")
        for comp in probe["components"]:
            for p in comp["properties"]:
                if p["name"] == "mesa:probe:result" and comp["name"] in results:
                    p["value"] = results[comp["name"]]
        return probe

    def test_pin_the_probe_did_not_find_is_lock_only(self):
        # tini has no scanner component. Probed 'ok' it is confirmed (test_pins); probed
        # 'mismatch' it is as unconfirmed as without a probe, and must say so.
        code, err = self.run_tool(probe=self.probe_with(tini="mismatch", go="mismatch"))
        self.assertEqual(code, 0, err)
        doc = load(self.out)
        tini = self.find(doc, "tini")
