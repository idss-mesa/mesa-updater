def load(name):
    """A fixture by name, or any JSON file by absolute path."""
    with open(os.path.join(FIXTURE, name), encoding="utf-8") as f:
        return json.load(f)


def read(path):
    with open(path, "rb") as f:
        return f.read()


def props(comp, prefix=""):
    return [(p["name"], p["value"]) for p in comp.get("properties", []) if p["name"].startswith(prefix)]


def prop(comp, name):
    return next((v for n, v in props(comp) if n == name), None)


def paths(comp):
    return [v for n, v in props(comp, "syft:location:") if n.endswith(":path")]


class Case(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="sbom-merge-case-")
        self.addCleanup(shutil.rmtree, self.tmp)
        self.out = os.path.join(self.tmp, "image.cdx.json")

    def write(self, name, doc):
        path = os.path.join(self.tmp, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(doc if isinstance(doc, str) else json.dumps(doc))
        return path

    def as_path(self, value, name):
        """A document is written to a file; a relative name is a fixture."""
        if isinstance(value, dict):
            return self.write(name, value)
        return value if value is None or os.path.isabs(value) else os.path.join(FIXTURE, value)

    def run_tool(self, image="image.cdx.json", locks=None, probe="probe.cdx.json", extras="extras.cdx.json",
                 **override):
        """Run main() in-process; return (exit code, stderr)."""
        args = {"image-sbom": self.as_path(image, "in-image.json"),
                "locks-sbom": self.as_path(locks or LOCKS, "in-locks.json"),
                "probe-sbom": self.as_path(probe, "in-probe.json"),
                "extras": self.as_path(extras, "in-extras.json"),
                "name": NAME, "digest": DIGEST, "version": "v2.0.0", "variant": "cpu", "arch": "amd64",
                "revision": REVISION, "timestamp": TIMESTAMP, "output": self.out}
        args.update({k.replace("_", "-"): v for k, v in override.items()})
        argv = [x for k, v in args.items() if v is not None for x in ("--" + k, v)]
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            try:
                code = sbom_merge.main(argv)
            except SystemExit as e:  # argparse
                code = e.code
        return code, err.getvalue()

    def merged(self, **kw):
        code, err = self.run_tool(**kw)
        self.assertEqual(code, 0, err)
        return load(self.out)

    def find(self, doc, name, under=None, version=None, ptype=None):
        """The one component of that name (and location prefix, version, purl type)."""
        hits = [c for c in doc["components"] if c["name"] == name
                and (version is None or c.get("version") == version)
                and (ptype is None or c.get("purl", "").startswith(f"pkg:{ptype}/"))
                and (under is None or any(p.startswith(under + "/") for p in paths(c))
                     or under in (prop(c, "mesa:lock:prefix"), prop(c, "mesa:probe:prefix")))]
        self.assertEqual(len(hits), 1, f"{name} under {under}: {[c['bom-ref'] for c in hits]}")
        return hits[0]


class Components(Case):
    def test_drops_files_and_package_id_and_refs_are_unique(self):
        image = load("image.cdx.json")
        self.assertEqual(sum(c["type"] == "file" for c in image["components"]), 4)
        self.assertIn("package-id=", image["components"][0]["bom-ref"])
        doc = self.merged()
        self.assertFalse([c for c in doc["components"] if c["type"] == "file"])
        self.assertNotIn("package-id", json.dumps(doc["components"]) + json.dumps(doc["dependencies"]))
        refs = [c["bom-ref"] for c in doc["components"]] + [doc["metadata"]["component"]["bom-ref"]]
        self.assertEqual(len(refs), len(set(refs)))
        self.assertTrue(all(isinstance(r, str) and r for r in refs))
        # every scanner package is still there, including the operating-system entry
        self.assertEqual(len([c for c in doc["components"] if props(c, "syft:")]), 99)
        self.assertEqual(self.find(doc, "ubuntu")["type"], "operating-system")

    def test_scanner_fields_survive(self):
        image = load("image.cdx.json")
        doc = self.merged()
        by_location = {(c["name"], c.get("version"), tuple(paths(c))): c for c in doc["components"]}
        checked = 0
        for old in image["components"]:
            if old["type"] == "file" or not paths(old):
                continue
            new = by_location[(old["name"], old.get("version"), tuple(paths(old)))]
            for field in old:
                if field == "bom-ref":
                    continue
                if field in ("properties", "externalReferences", "hashes"):
                    for item in old[field]:
                        self.assertIn(item, new[field], f"{old['name']}: lost a {field} entry")
                else:  # cpe, licenses, author, description, group, publisher, version, purl ...
                    self.assertEqual(new[field], old[field], f"{old['name']}.{field}")
            checked += 1
        self.assertEqual(checked, 98)

    def test_scanner_component_gains_lock_hashes_reference_and_properties(self):
        doc = self.merged()
        urllib3 = self.find(doc, "urllib3", under="/opt/mesa")
        self.assertEqual(urllib3["cpe"], "cpe:2.3:a:python:urllib3:2.8.0:*:*:*:*:*:*:*")
        self.assertEqual(sorted(h["alg"] for h in urllib3["hashes"]), ["SHA-256", "SHA-256"])
        self.assertEqual(dict(props(urllib3, "mesa:")), {
            "mesa:lock:kind": "pip", "mesa:lock:layer": "cpu",
            "mesa:lock:file": "sbom/pip/mesa-venv.amd64.txt", "mesa:lock:prefix": "/opt/mesa"})
        ajv = self.find(doc, "ajv", under=NPM)
        self.assertEqual([h["alg"] for h in ajv["hashes"]], ["SHA-512"])
        self.assertIn({"type": "distribution", "url": "https://registry.npmjs.org/ajv/-/ajv-8.20.0.tgz"},
                      ajv["externalReferences"])
        self.assertEqual(prop(ajv, "mesa:lock:prefix"), NPM)
        self.assertEqual(ajv["licenses"], [{"license": {"id": "MIT"}}])
        # the scanner's qualifier (vcs_url) is ignored when matching, and kept in the result
        ducklake = self.find(doc, "mesa-ducklake")
        self.assertIn("?vcs_url=", ducklake["purl"])
        self.assertEqual(prop(ducklake, "mesa:lock:kind"), "pip")
        self.assertIn("releases/download/v0.2.0/", ducklake["externalReferences"][-1]["url"])

    def test_same_package_in_other_prefixes_is_left_alone(self):
        doc = self.merged()
        # urllib3 2.8.0 is in three places; /opt/mesa and /opt/conda are locked (separately),
        # the copy in the nested conda env is not, although its path starts with /opt/conda/.
        self.assertEqual(prop(self.find(doc, "urllib3", under="/opt/mesa"), "mesa:lock:prefix"), "/opt/mesa")
        base = self.find(doc, "urllib3", under="/opt/conda/lib")
        self.assertEqual(prop(base, "mesa:lock:prefix"), "/opt/conda")
        self.assertEqual(prop(base, "mesa:lock:file"), "sbom/pip/conda-base.txt")
        env = self.find(doc, "urllib3", under=GEO + "/lib")
        self.assertEqual(props(env, "mesa:"), [])
        self.assertNotIn("hashes", env)
        # same name, other version, other prefix
        self.assertEqual(prop(self.find(doc, "jsonpointer", version="3.12"), "mesa:lock:prefix"), "/opt/mesa")
        self.assertEqual(props(self.find(doc, "jsonpointer", version="3.10"), "mesa:"), [])

