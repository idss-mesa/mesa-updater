def load(name):
    """A fixture by name, or any JSON file by absolute path."""
    with open(os.path.join(FIXTURE, name), encoding="utf-8") as f:
        return json.load(f)


def prop(comp, name):
    return next((p["value"] for p in comp.get("properties", []) if p["name"] == name), None)


def paths(comp):
    return [p["value"] for p in comp.get("properties", [])
            if p["name"].startswith("syft:location:") and p["name"].endswith(":path")]


def locks(drop=DRIFT, name="locks.tsv"):
    """The generated lock SBOM, by default without the three entries the real image does not match."""
    doc = json.loads(json.dumps(LOCKS[name]))
    doc["components"] = [c for c in doc["components"] if c["name"] not in drop]
    return doc


def relocate(comp, old, new):
    """Rewrite the location paths of a scanner component (all of them must change)."""
    for p in comp["properties"]:
        if p["name"].startswith("syft:location:") and p["name"].endswith(":path"):
            assert old in p["value"], p["value"]
            p["value"] = p["value"].replace(old, new)


def component(doc, name, under=None, version=None):
    """The one component of that name (and location prefix or mesa prefix, version)."""
    hits = [c for c in doc["components"] if c["name"] == name
            and (version is None or c.get("version") == version)
            and (under is None or any(p.startswith(under + "/") for p in paths(c))
                 or under in (prop(c, "mesa:lock:prefix"), prop(c, "mesa:probe:prefix")))]
    assert len(hits) == 1, f"{name} under {under}: {len(hits)} components"
    return hits[0]


class Case(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="sbom-crosscheck-case-")
        self.addCleanup(shutil.rmtree, self.tmp)
        self.report = os.path.join(self.tmp, "report.json")

    def write(self, name, content):
        path = os.path.join(self.tmp, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content if isinstance(content, str) else json.dumps(content))
        return path

    def as_path(self, value, name):
        """A document or TSV text is written to a file; a relative name is a fixture."""
        if isinstance(value, dict) or (isinstance(value, str) and ("\t" in value or "\n" in value)):
            return self.write(name, value)
        return value if value is None or os.path.isabs(value) else os.path.join(FIXTURE, value)

    def run_tool(self, lock=None, image="image.cdx.json", probe="probe.cdx.json", base=None, allow=None,
                 strict=False):
        """Run main() in-process; return (exit code, stdout, stderr)."""
        argv = ["--locks-sbom", self.as_path(lock or locks(), "in-locks.json"),
                "--image-sbom", self.as_path(image, "in-image.json"), "--report", self.report]
        for flag, value, name in (("--probe-sbom", probe, "in-probe.json"),
                                  ("--base-layers", base, "in-base-layers.txt"),
                                  ("--allow", allow, "in-allow.tsv")):
            if value is not None:
                argv += [flag, self.as_path(value, name)]
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = sbom_crosscheck.main(argv + (["--strict-reverse"] if strict else []))
        return code, out.getvalue(), err.getvalue()

    def check(self, expect=0, **kw):
        """Run, assert the exit code, return the report with rows keyed for lookup."""
        code, out, err = self.run_tool(**kw)
        self.assertEqual(code, expect, out + err)
        report = load(self.report)
        self.out = out
        self.forward = {(r["purl"], r["prefix"]): r for r in report["forward"]}
        self.reverse = report["reverse"]
        return report

    def fwd(self, purl, prefix=None):
        """(status, detail) of a lock component; purl may be given without qualifiers."""
        rows = [r for (p, pre), r in self.forward.items() if p.split("?")[0] == purl and pre == prefix]
        self.assertEqual(len(rows), 1, f"{purl} in {prefix}")
        return rows[0]["status"], rows[0]["detail"]

    def rev(self, purl, at=""):
        """(status, detail) of a scanner component, by purl without qualifiers (and detail text)."""
        rows = [r for r in self.reverse if (r["purl"] or "").split("?")[0] == (purl or "") and at in r["detail"]]
        self.assertEqual(len(rows), 1, f"{purl} {at}: {rows}")
        return rows[0]["status"], rows[0]["detail"]


class Forward(Case):
    def test_real_drift_fails(self):
        report = self.check(expect=1, lock=locks(drop=()))
        self.assertEqual(report["summary"]["forward"], {"missing": 1, "not-checked": 5, "ok": 54,
                                                         "unverifiable": 1, "version-mismatch": 2})
        self.assertEqual(report["summary"]["forward_by_kind"], {
            "base": {"not-checked": 1}, "conda": {"ok": 26}, "npm": {"missing": 1, "ok": 10},
            "pins": {"ok": 6, "unverifiable": 1}, "pip": {"ok": 12, "version-mismatch": 2},
            "vsix": {"not-checked": 4}})
        self.assertEqual(self.fwd("pkg:pypi/psycopg@3.3.9", "/opt/mesa"), ("version-mismatch", "image has 3.3.8"))
        self.assertEqual(self.fwd("pkg:pypi/psycopg-binary@3.3.9", "/opt/mesa")[0], "version-mismatch")
