class PerLocation(Case):
    """A component is explained when every location is, each by any mechanism."""

    def test_the_fixture(self):
        report = self.check(base="base-layers.txt", **LOCKED)
        self.assertEqual(report["summary"]["forward"], {"ok": 14})
        self.assertEqual(report["summary"]["reverse"], {"base-layer": 1, "lock": 15, "mixed": 1, "unexplained": 3})
        self.assertEqual(report["summary"]["reverse_by_type"], {
            "generic": {"lock": 1, "mixed": 1}, "npm": {"lock": 10, "unexplained": 1},
            "pypi": {"base-layer": 1, "lock": 4, "unexplained": 2}})

    def test_locations_may_be_explained_by_different_mechanisms(self):
        # /opt/conda/bin/openssl is in a base layer, the copy in the env is the conda lock's
        self.check(base="base-layers.txt", **LOCKED)
        self.assertEqual(self.rev("pkg:generic/openssl@3.6.5"), (
            "mixed", f"lock: conda package openssl 3.6.5 locked in {GEO}; base-layer: in a base image layer"))
        self.assertRegex(self.out, r"\n  type +lock +base-layer +mixed +unexplained\n")
        self.assertRegex(self.out, r"\n  generic +1 +0 +1 +0\n")
        # without the base layers one of the two locations has no explanation
        self.check(**LOCKED)
        self.assertEqual(self.rev("pkg:generic/openssl@3.6.5"), (
            "unexplained", "at /opt/conda/bin/openssl; explained: 1 of 2 locations"))
        self.assertNotIn("mixed", self.out)
        self.assertNotIn("mixed", load(self.report)["summary"]["reverse"])

    def test_one_unexplained_location_leaves_the_component_unexplained(self):
        image = load("locked-image.cdx.json")
        python = component(image, "python")
        self.assertEqual(paths(python), [GEO + "/bin/python3.10", GEO + "/lib/libpython3.10.so.1.0"])
        python["properties"][-1]["value"] = "/opt/elsewhere/libpython3.10.so.1.0"
        self.check(**dict(LOCKED, image=image))
        self.assertEqual(self.rev("pkg:generic/python@3.10.22"), (
            "unexplained", "at /opt/elsewhere/libpython3.10.so.1.0; explained: 1 of 2 locations"))
        # the same for a pin path and for a path rule
        image = load("image.cdx.json")
        node = component(image, "node")
        node["properties"].append({"name": "syft:location:1:path", "value": "/usr/local/bin/irods-mcp-server"})
        self.check(image=image)
        self.assertEqual(self.rev("pkg:generic/node@22.23.4"), (
            "unexplained", "at /usr/local/bin/irods-mcp-server; explained: 1 of 2 locations"))
        self.check(image=image, allow="path\t*\t/usr/local/bin/node\tthe node binary\n")
        self.assertEqual(self.rev("pkg:generic/node@22.23.4")[0], "unexplained")

    def test_status_is_the_shared_mechanism_or_mixed(self):
        image = load("image.cdx.json")
        node = component(image, "node")
        node["properties"].append({"name": "syft:location:1:path", "value": "/usr/local/bin/irods-mcp-server"})
