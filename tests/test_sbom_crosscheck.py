class Report(Case):
    def test_shape(self):
        report = self.check(base="base-layers.txt", allow="allow.tsv")
        self.assertEqual(sorted(report), ["forward", "reverse", "summary"])
        for row in report["forward"] + report["reverse"]:
            self.assertEqual(sorted(row), ["detail", "prefix", "purl", "status"])
        self.assertLessEqual({r["status"] for r in report["forward"]}, set(sbom_crosscheck.FORWARD))
        self.assertLessEqual({r["status"] for r in report["reverse"]}, set(sbom_crosscheck.REVERSE))
        self.assertEqual(sum(report["summary"]["forward"].values()), len(report["forward"]))
        self.assertEqual(sum(report["summary"]["reverse"].values()), len(report["reverse"]))
        self.assertEqual(len(report["forward"]), len(locks()["components"]))

    def test_report_is_optional_and_output_is_stable(self):
        argv = ["--locks-sbom", self.write("locks.json", locks()),
                "--image-sbom", os.path.join(FIXTURE, "image.cdx.json"),
                "--probe-sbom", os.path.join(FIXTURE, "probe.cdx.json")]
        outputs = []
        for _ in range(2):
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                self.assertEqual(sbom_crosscheck.main(argv), 0)
            outputs.append(out.getvalue())
        self.assertEqual(outputs[0], outputs[1])
        self.assertFalse(os.path.exists(self.report))
        self.assertIn("forward check: 60 lock components", outputs[0])
        self.assertIn("reverse check: 98 scanner components", outputs[0])

    def test_long_lists_are_cut_on_the_terminal_only(self):
        image = load("image.cdx.json")
        report = self.check(image=image)
        unexplained = report["summary"]["reverse"]["unexplained"]
        self.assertGreater(unexplained, sbom_crosscheck.SHOWN)
        self.assertEqual(self.out.count("\n  unexplained: "), sbom_crosscheck.SHOWN)
        self.assertIn(f"... and {unexplained - sbom_crosscheck.SHOWN} more unexplained (all in {self.report})",
                      self.out)

    def test_scales_to_a_real_scan(self):
        # 20k distinct packages, 5k of them locked, plus 40k file entries: seconds, not minutes
        image = load("image.cdx.json")
        ajv = json.dumps(component(image, "ajv"))
        lock = json.dumps(component(locks(), "ajv"))
        image["components"] = [{"bom-ref": f"f{i}", "type": "file", "name": f"/srv/f{i}"} for i in range(40000)]
        image["components"] += [json.loads(ajv.replace("ajv", f"pkg{i}")) for i in range(20000)]
        lock = {"bomFormat": "CycloneDX",
                "components": [json.loads(lock.replace("ajv", f"pkg{i}")) for i in range(0, 20000, 4)]}
        started = time.monotonic()
        report = self.check(image=image, lock=lock, probe=None)
        self.assertLess(time.monotonic() - started, 60)
        self.assertEqual(report["summary"]["forward"], {"ok": 5000})
        self.assertEqual(report["summary"]["reverse"], {"lock": 5000, "unexplained": 15000})


class Output(Case):
    """What the image says reaches the terminal as text, never as extra lines or escapes."""

    FORGED = "\n::error title=Injected::forged\n::add-mask::PASS\n\x1b[2K\rsbom_crosscheck: PASS"

    def assert_plain(self, out):
        lines = out.split("\n")
        self.assertEqual([line for line in lines if not line.isprintable()], [])
        self.assertEqual([line for line in lines if line.startswith("::")], [])
        self.assertEqual([line for line in lines if line.startswith("sbom_crosscheck:")], lines[-2:-1])

    def test_strings_from_the_image_are_printed_on_their_own_line(self):
        image = {"bomFormat": "CycloneDX", "components": [
            # a file path, as syft reports a directory name with newlines in it
            {"type": "library", "name": "evil", "version": "1", "purl": "pkg:npm/evil@1", "properties": [
                {"name": "syft:location:0:path",
                 "value": "/opt/x/node_modules/evil" + self.FORGED + "/package.json"}]},
            # no purl: name and version are shown
            {"type": "application", "name": "bin" + self.FORGED, "version": "1\n::notice::from-version",
             "properties": [{"name": "syft:location:0:path", "value": "/usr/local/bin/x"}]},
            # the purl itself, and its type (a table label)
            {"type": "library", "name": "z", "purl": "pkg:npm/z@1?x=" + self.FORGED},
            {"type": "library", "name": "y", "purl": "pkg:gem\n::error::from-type/y@1"},
            # a percent-encoded version, decoded for the forward check
            {"type": "library", "name": "foo", "purl": "pkg:npm/foo@9%0A::warning::forged%0A%1B[2K", "properties": [
                {"name": "syft:location:0:path", "value": "/opt/n/node_modules/foo/package.json"}]},
        ]}
        lock = {"bomFormat": "CycloneDX", "components": [
            {"type": "library", "name": "foo", "version": "1.0", "purl": "pkg:npm/foo@1.0", "properties": [
                {"name": "mesa:lock:kind", "value": "npm"}, {"name": "mesa:lock:prefix", "value": "/opt/n"}]}]}
        report = self.check(expect=1, lock=lock, image=image, probe=None)
        self.assert_plain(self.out)
        self.assertIn("  version-mismatch: pkg:npm/foo@1.0 in /opt/n: image has 9?::warning::forged??[2K\n", self.out)
        self.assertIn("  unexplained: pkg:npm/evil@1 at /opt/x/node_modules/evil?::error title=Injected::forged?"
                      "::add-mask::PASS??[2K?sbom_crosscheck: PASS/package.json\n", self.out)
        self.assertIn("?::notice::from-version at /usr/local/bin/x\n", self.out)
        self.assertIn("\n  gem?::error::from-type ", self.out)
        self.assertEqual(self.out.count("\n  unexplained: "), 5)
        # the report is data for a program: values as they are
        self.assertEqual(self.fwd("pkg:npm/foo@1.0", "/opt/n")[1], "image has 9\n::warning::forged\n\x1b[2K")
        self.assertIn("at /opt/x/node_modules/evil" + self.FORGED + "/package.json",
                      [r["detail"] for r in report["reverse"]])

    def test_real_fixtures_print_the_same_with_and_without_the_filter(self):
        self.check(expect=1, lock=locks(drop=()), base="base-layers.txt", allow="allow.tsv")
        self.assert_plain(self.out)
        self.assertNotIn("?", self.out)


class BadInput(Case):
    def assert_bad(self, needle, **kw):
        code, out, err = self.run_tool(**kw)
        self.assertEqual(code, 2, out + err)
        self.assertIn(needle, err)
        self.assertEqual(out, "")
        self.assertFalse(os.path.exists(self.report))

    def test_malformed_json_names_file_and_line(self):
        path = self.write("broken.json", '{"bomFormat": "CycloneDX",\n "components": [\n  {"name": ]}\n')
        for kw in ({"lock": path}, {"image": path}, {"probe": path}):
            self.assert_bad(f"{path}:3: invalid JSON", **kw)

    def test_missing_and_foreign_files(self):
        self.assert_bad("No such file", image=os.path.join(self.tmp, "absent.json"))
        self.assert_bad("No such file", allow=os.path.join(self.tmp, "absent.tsv"))
        self.assert_bad("No such file", base=os.path.join(self.tmp, "absent.txt"))
        self.assert_bad("not a CycloneDX document", image=self.write("spdx.json", {"spdxVersion": "SPDX-2.3"}))
        self.assert_bad("components[0] is not an object with a name",
                        image={"bomFormat": "CycloneDX", "components": [[]]})

    def test_json_shapes_that_cannot_be_indexed(self):
        deep = self.write("deep.json", "[" * 100000 + "]" * 100000)
        for kw in ({"lock": deep}, {"image": deep}, {"probe": deep}):
            self.assert_bad(f"{deep}: invalid JSON: nested too deeply", **kw)

        def doc(component=None, **more):
            return dict({"bomFormat": "CycloneDX", "components": [dict({"name": "a"}, **(component or {}))]}, **more)
        self.assert_bad("components[0]: bom-ref is not a string", image=doc({"bom-ref": ["x"]}))
        self.assert_bad("dependencies is not a list of objects with a ref",
                        image=doc(dependencies=[{"ref": {"a": 1}, "dependsOn": []}]))

    def test_lock_sbom_must_be_one(self):
        # a scanner SBOM in place of the lock SBOM
        self.assert_bad("not a lock component", lock=os.path.join(FIXTURE, "image.cdx.json"))
        lock = locks()
        component(lock, "ajv")["properties"][0]["value"] = "apt"
        self.assert_bad("(pkg:npm/ajv@8.20.0#" + NPM + "): not a lock component", lock=lock)
        lock = locks()
        ajv = component(lock, "ajv")
        ajv["properties"] = [p for p in ajv["properties"] if p["name"] != "mesa:lock:prefix"]
        self.assert_bad("kind 'npm' needs mesa:lock:prefix", lock=lock)

    def test_allow_tsv(self):
        good = "purl-type\t*\tdeb\tfrom apt\n"
        for bad, message in (
                ("purl-type\t*\tdeb\n", "expected 4 tab-separated columns, got 3"),
                ("purl-type * deb reason\n", "expected 4 tab-separated columns, got 1"),
                ("package\t*\tdeb\tr\n", "unknown rule 'package'"),
                ("purl-type\tbase\tdeb\tr\n", "unknown layer 'base'"),
                ("purl-type\t*\tdeb\t \n", "a reason is required"),
                ("purl-type\t*\tpkg:deb\tr\n", "'pkg:deb' is not a purl type"),
                ("path\t*\topt/conda\tr\n", "path 'opt/conda' is not absolute"),
                ("purl\t*\tdeb/ubuntu/adduser@1\tr\n", "is not pkg:<type>/<name>@<version or *>"),
                ("purl\t*\tpkg:deb/ubuntu/adduser\tr\n", "is not pkg:<type>/<name>@<version or *>"),
                ("purl\t*\tpkg:deb/ubuntu/adduser@1?arch=all\tr\n", "without qualifiers")):
            path = self.write("allow.tsv", "# comment\n\n" + good + bad)
            self.assert_bad(f"{path}:4: ", allow=path)
            self.assert_bad(message, allow=path)

    def test_base_layers(self):
        good = "sha256:" + "a" * 64
        path = self.write("layers.txt", f"# base\n{good}\n5cac300e390e\n")
        self.assert_bad(f"{path}:3: '5cac300e390e' is not a sha256: diff ID", base=path)
        path = self.write("layers.txt", f"{good}\tlayer 1\n")
        self.assert_bad(f"{path}:1: expected 1 tab-separated columns", base=path)

    def test_missing_argument(self):
        err = io.StringIO()
        with contextlib.redirect_stderr(err), self.assertRaises(SystemExit) as caught:
            sbom_crosscheck.main(["--locks-sbom", "x"])
        self.assertEqual(caught.exception.code, 2)
        self.assertIn("--image-sbom", err.getvalue())

    def test_unwritable_report(self):
        self.report = os.path.join(self.tmp, "no-such-dir", "report.json")
        code, _, err = self.run_tool()
        self.assertEqual(code, 2)
        self.assertIn("report.json: No such file or directory", err)


